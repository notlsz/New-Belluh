// Keeps the growth playbook honest about what the product actually does in each market.
// Reads the code (country kits, love calendars, crisis lines, UI languages, Bella's channels) and rewrites the
// "Shipped in the product" block of every market file plus the status table in docs/growth/README.md.
// Run after any market work: node scripts/growth-status.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const read = p => readFileSync(join(root, p), 'utf8');
const block = (src, start) => { const i = src.indexOf(start); if (i < 0) return ''; const j = src.indexOf('\n};', i); return src.slice(i, j); };

const kits = new Set([...block(read('supabase/functions/_shared/region.ts'), 'export const KITS').matchAll(/^ {2}([A-Z]{2}): \{/gm)].map(m => m[1]));
const love = new Set([...block(read('supabase/functions/_shared/jarvis.ts'), 'const LOVE_DAYS').matchAll(/^ {2}([A-Z]{2}): \[/gm)].map(m => m[1]));
const crisis = new Set([...block(read('supabase/functions/_shared/safety.ts'), 'const LINES').matchAll(/^ {2}([A-Z]{2}): /gm)].map(m => m[1]));
const core = read('src/i18n/core.ts');
const langs = new Set([...core.matchAll(/id: '([a-zA-Z-]+)'/g)].map(m => m[1]));
for (const v of ['es-MX', 'pt-PT', 'zh-Hant']) if (core.includes(`'${v}'`)) langs.add(v);
const channelSrc = read('supabase/functions/_shared/agentcore.ts').match(/export type Channel = ([^;]+);/)?.[1] ?? '';
const channels = new Set([...channelSrc.matchAll(/'([a-z]+)'/g)].map(m => m[1]).filter(c => c !== 'app'));

const CH = { iMessage: 'imessage', WhatsApp: 'whatsapp', Messenger: 'messenger', KakaoTalk: 'kakao', LINE: 'line', Zalo: 'zalo', Viber: 'viber', Telegram: 'telegram', WeChat: 'wechat', SMS: 'sms', RCS: 'sms' };
const index = JSON.parse(read('docs/growth/markets/index.json'));
const yes = b => (b ? 'yes' : '**no**');
const today = new Date().toISOString().slice(0, 10);
const rows = [];

for (const [iso, m] of Object.entries(index)) {
  const path = `docs/growth/markets/${m.file}`;
  let doc = read(path);
  const channelRow = doc.match(/^\| Channel \| (.+)$/m)?.[1] ?? '';
  const named = Object.keys(CH).map(k => [k, channelRow.indexOf(k)]).filter(([, i]) => i >= 0).sort((a, b) => a[1] - b[1]);
  const primary = named[0]?.[0] ?? null;
  const primaryOk = primary ? channels.has(CH[primary]) : null;
  const wanted = (m.langs || '').split(',').map(s => s.trim()).filter(Boolean);
  const base = l => l.split('-')[0];
  const langOk = wanted.length ? wanted.some(l => langs.has(l) || (l !== 'zh-Hant' && langs.has(base(l)))) : null;
  const status = [
    `Generated by scripts/growth-status.mjs from the code on ${today}. Do not edit by hand.`,
    '',
    `| Piece | Shipped |`,
    `|---|---|`,
    `| Country kit (local sites, culture, prices) in region.ts | ${yes(kits.has(iso))} |`,
    `| Love calendar in jarvis.ts | ${yes(love.has(iso))} |`,
    `| Local crisis line in safety.ts | ${crisis.has(iso) ? 'yes' : '**no** (generic fallback)'} |`,
    `| UI language (${wanted.join(', ') || 'n/a'}) | ${langOk === null ? 'n/a' : yes(langOk)} |`,
    `| Bella on the main local channel (${primary ?? 'unknown'}) | ${primaryOk === null ? 'n/a' : yes(primaryOk)} |`,
  ].join('\n');
  doc = doc.replace(/<!-- status:start -->[\s\S]*?<!-- status:end -->/, `<!-- status:start -->\n${status}\n<!-- status:end -->`);
  writeFileSync(join(root, path), doc);
  const ready = [kits.has(iso), love.has(iso), crisis.has(iso), langOk !== false, primaryOk !== false].filter(Boolean).length;
  rows.push({ iso, m, kit: kits.has(iso), love: love.has(iso), crisis: crisis.has(iso), langOk, primary, primaryOk, ready });
}

rows.sort((a, b) => (a.m.rank ?? 999) - (b.m.rank ?? 999));
const mark = b => (b === null ? 'n/a' : b ? 'yes' : 'no');
const table = [
  `Generated by scripts/growth-status.mjs on ${today}. Bella's channels today: ${[...channels].join(', ')}. UI languages: ${[...langs].join(', ')}.`,
  '',
  '| Rank | Market | Wave | Kit | Love days | Crisis line | UI language | Main channel | Ready |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.m.rank ?? '-'} | [${r.m.name}](markets/${r.m.file}) | ${r.m.wave} | ${mark(r.kit)} | ${mark(r.love)} | ${mark(r.crisis)} | ${mark(r.langOk)} | ${r.primary ?? '?'}: ${mark(r.primaryOk)} | ${r.ready}/5 |`),
].join('\n');
const readme = read('docs/growth/README.md').replace(/<!-- table:start -->[\s\S]*?<!-- table:end -->/, `<!-- table:start -->\n${table}\n<!-- table:end -->`);
writeFileSync(join(root, 'docs/growth/README.md'), readme);
console.log(`Updated ${rows.length} markets. Kits ${kits.size}, love calendars ${love.size}, crisis lines ${crisis.size}, languages ${langs.size}, channels ${channels.size}.`);
